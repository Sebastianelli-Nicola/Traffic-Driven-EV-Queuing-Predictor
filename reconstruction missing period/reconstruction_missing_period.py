"""## 5. Validazione Statistica: Contesto Macro vs Contesto Micro
Per dimostrare l'accuratezza del modello rispetto ai cali fisiologici di traffico e alla preservazione del pattern giornaliero, si implementa una dashboard analitica per stazione (2x2).
Si calcolano metriche come l'Errore Relativo e la Correlazione di Pearson (Shape Similarity) mettendo a confronto il dato generato (Luglio) con il **Macro-Contesto** (intero mese di Giugno) e il **Micro-Contesto** (la settimana di traffico precedente e successiva al gap). Questo permette di valutare quantitativamente come l'algoritmo si agganci alla reale temperatura di traffico estivo isolandola dai volumi invernali.
"""

# ==============================================================================
# 5. VALIDAZIONE STATISTICA MACRO (Giugno) E MICRO (Settimane Adiacenti)
# ==============================================================================
print("Esecuzione della suite di validazione avanzata...\n")

# Definiamo le finestre temporali esatte (1 Settimana)
pre_start = gap_start - pd.Timedelta(days=7)
post_end = gap_end + pd.Timedelta(days=7)

validation_metrics = []

sns.set_theme(style="whitegrid")
stazioni = sorted(df_final['id_stazione'].unique())

for st in stazioni:
    df_st = df_final[df_final['id_stazione'] == st].copy()

    # --- 1. Creazione Maschere per i 4 Periodi di Riferimento ---
    m_june = df_st['timestamp'].dt.month == 6
    m_rec = (df_st['timestamp'] >= gap_start) & (df_st['timestamp'] <= gap_end)
    m_pre = (df_st['timestamp'] >= pre_start) & (df_st['timestamp'] < gap_start)
    m_post = (df_st['timestamp'] > gap_end) & (df_st['timestamp'] <= post_end)

    # Estrazione subset
    df_june = df_st[m_june]
    df_rec = df_st[m_rec]
    df_pre = df_st[m_pre]
    df_post = df_st[m_post]

    # Il Contesto Locale complessivo è la fusione tra Pre e Post
    df_local = pd.concat([df_pre, df_post])

    # --- 2. Calcolo Profili Orari Medi ---
    def get_hourly_profile(df_subset):
        if df_subset.empty: return pd.Series(np.nan, index=np.arange(24))
        return df_subset.groupby(df_subset['timestamp'].dt.hour)['differenza'].mean()

    prof_june = get_hourly_profile(df_june)
    prof_rec = get_hourly_profile(df_rec)
    prof_pre = get_hourly_profile(df_pre)
    prof_post = get_hourly_profile(df_post)
    prof_local = get_hourly_profile(df_local) # Profilo medio delle due settimane reali adiacenti

    # --- 3. Calcolo Metriche Statistiche ---
    mean_june = prof_june.mean()
    mean_rec = prof_rec.mean()
    mean_local = prof_local.mean()

    # Errore Relativo %
    err_rel_june = abs(mean_rec - mean_june) / mean_june * 100 if mean_june > 0 and not pd.isna(mean_rec) else 0.0
    err_rel_local = abs(mean_rec - mean_local) / mean_local * 100 if mean_local > 0 and not pd.isna(mean_rec) else 0.0

    # Correlazione di Pearson (Gestita per varianze zero)
    def calc_corr(p1, p2):
        corr = p1.corr(p2)
        if pd.isna(corr):
            return 1.0 if p1.std() == 0 and p2.std() == 0 else 0.0
        return corr

    corr_june = calc_corr(prof_rec, prof_june)
    corr_local = calc_corr(prof_rec, prof_local)

    validation_metrics.append({
        'Stazione': st,
        'Media Ricostruita': mean_rec,
        'Target MACRO (Giugno)': mean_june,
        'Target MICRO (Pre+Post)': mean_local,
        'Err % (vs Giugno)': err_rel_june,
        'Err % (vs Micro)': err_rel_local,
        'Corr (vs Giugno)': corr_june,
        'Corr (vs Micro)': corr_local
    })

    # --- 4. PLOTTING DASHBOARD 2x2 ---
    fig = plt.figure(figsize=(20, 10))
    gs = fig.add_gridspec(2, 2)
    fig.suptitle(f"Validazione Stazione {st} - Macro Contesto (Giugno) vs Micro Contesto (Pre/Post Gap)", fontsize=16, fontweight='bold', y=1.02)

    # Plot 1: Zoom Temporale (Pre, Gap, Post)
    ax1 = fig.add_subplot(gs[0, 0])
    # Dati di sfondo per dare contesto visivo (14 gg prima e dopo)
    bg_start = pre_start - pd.Timedelta(days=7)
    bg_end = post_end + pd.Timedelta(days=7)
    ax1.plot(df_st[(df_st['timestamp'] >= bg_start) & (df_st['timestamp'] <= bg_end)]['timestamp'],
             df_st[(df_st['timestamp'] >= bg_start) & (df_st['timestamp'] <= bg_end)]['differenza'],
             color='lightgray', linewidth=1, alpha=0.5)

    ax1.scatter(df_pre['timestamp'], df_pre['differenza'], color='forestgreen', s=10, label='Pre-Gap (1 Set)')
    ax1.scatter(df_rec['timestamp'], df_rec['differenza'], color='darkorange', s=10, label='Ricostruito')
    ax1.scatter(df_post['timestamp'], df_post['differenza'], color='mediumpurple', s=10, label='Post-Gap (1 Set)')

    ax1.axvline(gap_start, color='red', linestyle='--', alpha=0.4)
    ax1.axvline(gap_end, color='red', linestyle='--', alpha=0.4)
    ax1.set_title("1. Continuità Temporale nel Micro Contesto")
    ax1.tick_params(axis='x', rotation=45)
    ax1.legend(loc='upper right', fontsize='small')
    ax1.set_ylabel("Diff. Velocità (km/h)")

    # Plot 2: Distribuzione Densità Valori (KDE) - Focus su Pre/Post/Ricostruito
    ax2 = fig.add_subplot(gs[0, 1])
    datasets = [('Pre-Gap (Reale)', df_pre['differenza'], 'forestgreen'),
                ('Ricostruito', df_rec['differenza'], 'darkorange'),
                ('Post-Gap (Reale)', df_post['differenza'], 'mediumpurple')]

    for label, data, color in datasets:
        data = data.dropna()
        if len(data) > 1 and data.std() > 0:
            sns.kdeplot(data, ax=ax2, fill=True, label=label, color=color, alpha=0.2, linewidth=2)
        elif len(data) > 0:
            ax2.axvline(data.mean(), color=color, linestyle='--', label=f"{label} (Costante)")

    ax2.set_title("2. Distribuzione Densità Valori (Volume di Traffico)")
    ax2.set_xlabel("Differenza (km/h)")
    ax2.set_yticks([])
    ax2.legend(fontsize='small')

    # Plot 3: Profilo Orario (MACRO: Giugno vs Ricostruito)
    ax3 = fig.add_subplot(gs[1, 0])
    ax3.plot(prof_june.index, prof_june, label='Media Giugno (Reale)', color='steelblue', linewidth=2, linestyle='--')
    ax3.plot(prof_rec.index, prof_rec, label='Ricostruito', color='darkorange', linewidth=3)

    ax3.set_title(f"3. Profilo MACRO (Shape Corr vs Giugno: {corr_june:.2f})")
    ax3.set_xlabel("Ora del Giorno")
    ax3.set_ylabel("Media km/h")
    ax3.legend(fontsize='small')

    # Plot 4: Profilo Orario (MICRO: Pre vs Post vs Ricostruito)
    ax4 = fig.add_subplot(gs[1, 1])
    ax4.plot(prof_pre.index, prof_pre, label='Pre-Gap', color='forestgreen', linewidth=1.5, linestyle='-.', alpha=0.7)
    ax4.plot(prof_post.index, prof_post, label='Post-Gap', color='mediumpurple', linewidth=1.5, linestyle=':', alpha=0.7)

    # Creiamo una linea grigia tratteggiata per la media tra Pre e Post
    ax4.plot(prof_local.index, prof_local, label='Media (Pre+Post)', color='black', linewidth=2, linestyle='--', alpha=0.5)
    ax4.plot(prof_rec.index, prof_rec, label='Ricostruito', color='darkorange', linewidth=3)

    ax4.set_title(f"4. Profilo MICRO (Shape Corr vs Pre+Post: {corr_local:.2f})")
    ax4.set_xlabel("Ora del Giorno")
    ax4.set_ylabel("Media km/h")
    ax4.legend(fontsize='small')

    plt.tight_layout()
    plt.show()

