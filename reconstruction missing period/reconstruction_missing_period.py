"""## 2. Funzioni Core dell'Algoritmo (Ricostruzione)
Qui si definiscono le funzioni matematiche centrali dell'algoritmo:
1. **Ricerca Periodi Analoghi (`find_analogous_periods`)**: Seleziona i giorni storici più simili utilizzando una gerarchia di punteggi rigida (Ora > Giorno > Recenza Bidirezionale).
2. **Ricostruzione per Campionamento (`reconstruct_station_by_sampling`)**: Calcola il valore atteso aggregando i candidati scelti e iniettando una perturbazione gaussiana basata sulla sola varianza locale. Applica un limite calcolato sulla media dei picchi pre e post gap.
3. **Cross-Validation a 1 Settimana (`grid_search_reconstruction`)**: Cerca i parametri ottimali simulando buchi finti nei giorni strettamente adiacenti al gap reale.
4. **Sfumatura (`smooth_transitions`)**: Garantisce la continuità della curva ai bordi del gap.

Nello specifico queste sono le 4 funzioni principali:

1.  **`find_analogous_periods` (Ricerca Storica Bidirezionale)**
    Questa funzione ha il compito di trovare i giorni passati (o futuri) che più assomigliano al momento che si sta tentando di ricostruire. Per farlo, non usa una semplice finestra temporale, ma applica una **Gerarchia Rigida di Punteggi**:
    * **Ora esatta (+100 punti):** Garantisce che le dinamiche del mattino non vengano mai confuse con quelle serali o notturne.
    * **Giorno della settimana (+50 punti):** Mantiene la separazione critica tra i giorni feriali (pendolarismo) e i festivi.
    * **Recenza Bidirezionale (+20 punti a scalare):** Funge da *tie-breaker*. Se l'algoritmo trova molti "Lunedì alle 08:00", preferirà quelli temporalmente più vicini al buco da coprire. La misurazione è bidirezionale: se si sta ricostruendo la prima metà del buco, cercherà i giorni passati adiacenti; se si sta ricostruendo la seconda metà, darà priorità ai giorni futuri adiacenti. Questo garantisce un perfetto ancoraggio alla stagionalità locale.

2.  **`reconstruct_station_by_sampling` (Imputazione con Iniezione Stocastica)**
    È qui che avviene la generazione materiale del dato. Per ogni singolo slot di tempo mancante (es. 10 minuti), l'algoritmo estrae i candidati ottimali calcolati dalla funzione precedente.
    * **Valore Base:** Viene calcolata la media aritmetica dei candidati migliori.
    * **Iniezione del Rumore:** L'algoritmo calcola quindi la **Deviazione Standard Locale** all'interno dei candidati stessi. Se i candidati storici oscillavano molto (traffico instabile), la deviazione standard sarà alta. Se i candidati erano tutti a zero (strada libera), la deviazione sarà zero. Questo valore diventa il parametro `scale` di una distribuzione Gaussiana (Normale). L'algoritmo "lancia un dado" seguendo questa curva a campana e somma il risultato al Valore Base. In questo modo, le strade storicamente fluide rimangono piatte a zero, mentre i momenti di congestione mantengono una naturale turbolenza.
    * **Clipping:** Per evitare che il rumore generi picchi innaturali o valori negativi, il dato finale viene limitato tra zero e la media matematica dei picchi massimi registrati nelle due settimane adiacenti al buco.

3.  **`grid_search_reconstruction` (Ottimizzazione dei Parametri via Cross-Validation)**
    L'algoritmo non utilizza parametri fissi per tutte le stazioni geografiche. Prima di ricostruire il gap reale, questa funzione crea due "finti buchi" della durata di 7 giorni immediatamente prima e immediatamente dopo il periodo mancante reale. Testa diverse combinazioni di parametri (quanti candidati storici guardare e quanti usarne per la media) confrontando i dati generati con i dati reali nascosti, calcolando il *Mean Absolute Error* (MAE). I parametri che minimizzano l'errore nel micro-contesto locale verranno poi utilizzati per l'imputazione definitiva.

4.  **`smooth_transitions` (Raccordo ai Bordi)**
    Infine, per garantire che non vi siano "scalini" innaturali nel momento in cui la serie storica reale si interrompe e inizia quella ricostruita (e viceversa), questa funzione applica una sfumatura lineare. Funziona come un *fade-in* e un *fade-out* audio: i primi e gli ultimi dati generati vengono ponderatamente miscelati con la media mobile dei dati reali immediatamente adiacenti, garantendo una continuità fluida e senza strappi.
"""

